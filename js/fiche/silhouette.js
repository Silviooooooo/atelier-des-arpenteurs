function carre(code, armure) {
  const { x, y } = CARRES[code];
  const zone = ZONE[code];
  const largeur = LARGEUR_ENDURANCE / RESISTANCE_PAR_ZONE;
  const milieu = x + COTE / 2;
  // Le torse est sur la forme : ses textes prennent la couleur qui s'y lit.
  const classeNom = code === "torse" ? "nom-zone-svg sur-silhouette" : "nom-zone-svg";
  const tete = code === "tete";
  return svg(
    "g",
    {},
    svg("rect", { classe: "cadre-zone", x: x + 1.5, y: y + 1.5, width: 89, height: 89 }),
    Array.from({ length: RESISTANCE_PAR_ZONE }, (_, i) =>
      svg("rect", { classe: "case-endurance", x: (x + 3 + i * largeur).toFixed(1), y: y + 71.5, width: largeur.toFixed(1), height: 17.5 }),
    ),
    svg("text", { classe: "valeur-armure", x: x + 8, y: y + 21 }, armure ?? ""),
    svg("text", { classe: classeNom, x: milieu, y: y - 8 }, tete ? `${zone.abrege} : ${zone.d20}` : zone.abrege),
    tete ? null : svg("text", { classe: classeNom, x: milieu, y: y + COTE + 23 }, zone.d20),
  );
}

/** La silhouette et ses six zones ; zones : l'armure de chaque zone, par code. */
export function silhouette(zones) {
  return svg(
    "svg",
    { classe: "silhouette-zones", viewBox: "0 0 479 604", role: "img", "aria-label": "Localisation : armure et endurance des six zones" },
    svg("path", { classe: "forme-silhouette", transform: "translate(0 8)", d: FORME }),
    Object.keys(CARRES).map((code) => carre(code, zones[code])),
  );
}
